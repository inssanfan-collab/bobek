/**
 * Тарифы. Единственное место, где описано, чем они отличаются: на главной,
 * в тарифах, в заявке, в оферте и в договоре должен быть один и тот же
 * смысл, иначе сад прочитает на сайте одно, а подпишет другое.
 *
 * Цен здесь нет — они в настройках приложения (`env.planPrices`), чтобы
 * менять их без правки кода. Модуль без серверных зависимостей: его
 * читает и форма заявки в браузере.
 *
 * Разница между тарифами одна — кто наполняет сайт. Движок, админка,
 * хостинг и поддержка одинаковые. Домен на edu.kz не входит ни в один:
 * сад покупает его сам, мы помогаем настроить.
 */

export const PLAN_CODES = ['BASIC', 'MANAGED'] as const;
export type PlanCode = (typeof PLAN_CODES)[number];

export function isPlanCode(value: unknown): value is PlanCode {
  return typeof value === 'string' && (PLAN_CODES as readonly string[]).includes(value);
}

