/**
 * Когда подписка закончилась.
 *
 * Льготных дней нет: не оплачено — сайт закрыт. Но последний оплаченный день
 * сад получает целиком. «Подписка до 10 сентября» в карточке и в договоре
 * читается как «10 сентября ещё работаем», поэтому закрываемся с 11-го,
 * а не в полночь на 10-е.
 *
 * Модуль без зависимостей: его читают и приложение, и утренний скрипт
 * проверки подписок — правило обязано быть одно.
 */

const DAY_MS = 24 * 60 * 60 * 1000;

export function periodIsOver(periodEnd: Date, now: number = Date.now()): boolean {
  return now >= periodEnd.getTime() + DAY_MS;
}
